% function to create base filename from design parameters

function P = CreateFileBase(P)

if isfield(P,'celltype') && strcmp(P.celltype,'blockTet')
    P.fileBase = ['a',num2str(P.a*1e9,'%.0f'),'nm_',...
              'w',num2str(P.w*1e9,'%.0f'),'nm_',...
              'hx',num2str(P.hx*1e9,'%.0f'),'nm_',...
              'hy',num2str(P.hy*1e9,'%.0f'),'nm_',...
              'nh',num2str(P.nholes,'%.0f'),'_',...
              'nd',num2str(P.ndef,'%.0f'),'_',...
              'aD',num2str(P.a_ctr*1e9,'%.0f'),'nm_',...
              'wD',num2str(P.w_ctr*1e9,'%.0f'),'nm_',...
              'hxD',num2str(P.hx_ctr*1e9,'%.0f'),'nm_',...
              'hyD',num2str(P.hy_ctr*1e9,'%.0f'),'nm_',...
              'X',num2str(P.mevenx),...
              'Y',num2str(P.meveny),...
              'Z',num2str(P.mevenz)];
elseif isfield(P,'celltype') && strcmp(P.celltype,'boomerang_v2')
    P.fileBase = ['boomerang_v2_','a',num2str(P.a*1e9,'%.0f'),'nm_',...
              'w',num2str(P.w*1e9,'%.0f'),'nm_',...
              'r',num2str(P.r*1e9,'%.0f'),'nm_',...
              'hi',num2str(P.hi*1e9,'%.0f'),'nm_',...
              'ho',num2str(P.ho*1e9,'%.0f'),'nm_',...
              'wi',num2str(P.wi*1e9,'%.0f'),'nm_',...
              'wo',num2str(P.wo*1e9,'%.0f'),'nm_',...
              'd',num2str(P.d*1e9,'%.0f'),'nm_',...
              'th',num2str(P.th*1e9,'%.0f'),'nm_',...
              'a_ctr',num2str(P.a_ctr*1e9,'%.0f'),'nm_',...
              'ho_ctr',num2str(P.ho_ctr*1e9,'%.0f'),'nm_',...
              'hi_ctr',num2str(P.hi_ctr*1e9,'%.0f'),'nm_',...
              'wo_ctr',num2str(P.wo_ctr*1e9,'%.0f'),'nm_',...
              'wi_ctr',num2str(P.wi_ctr*1e9,'%.0f'),'nm_',...
              'MN_left',num2str(P.MN_left,'%.0f'),'_',...
              'MN_right',num2str(P.MN_right,'%.0f'),'_',...
              'TN',num2str(P.TN,'%.0f'),'_',...
              'X',num2str(P.mevenx),...
              'Y',num2str(P.meveny),...
              'Z',num2str(P.mevenz)];
elseif isfield(P,'celltype') && strcmp(P.celltype,'snowflake')
    P.fileBase = ['snowflake_','a',num2str(P.a*1e9,'%.0f'),'nm_',...
              'w',num2str(P.w*1e9,'%.0f'),'nm_',...
              'r',num2str(P.r*1e9,'%.0f'),'nm_',...
              'hi',num2str(P.hi*1e9,'%.0f'),'nm_',...
              'ho',num2str(P.ho*1e9,'%.0f'),'nm_',...
              'wi',num2str(P.wi*1e9,'%.0f'),'nm_',...
              'wo',num2str(P.wo*1e9,'%.0f'),'nm_',...
              'd',num2str(P.d*1e9,'%.0f'),'nm_',...
              'th',num2str(P.th*1e9,'%.0f'),'nm_',...
              'a_ctr',num2str(P.a_ctr*1e9,'%.0f'),'nm_',...
              'ho_ctr',num2str(P.ho_ctr*1e9,'%.0f'),'nm_',...
              'hi_ctr',num2str(P.hi_ctr*1e9,'%.0f'),'nm_',...
              'wo_ctr',num2str(P.wo_ctr*1e9,'%.0f'),'nm_',...
              'wi_ctr',num2str(P.wi_ctr*1e9,'%.0f'),'nm_',...
              'MN_left',num2str(P.MN_left,'%.0f'),'_',...
              'MN_right',num2str(P.MN_right,'%.0f'),'_',...
              'TN',num2str(P.TN,'%.0f'),'_',...
              'X',num2str(P.mevenx),...
              'Y',num2str(P.meveny),...
              'Z',num2str(P.mevenz)];
elseif isfield(P,'celltype') && strcmp(P.celltype,'rib')
    % rib cavity (createRibCavityGeom / buildRibCavity). Keep this branch
    % identical in CreateFileBase.m and nanobeam/CreateFileBase.m. Values are
    % read after defaults so the name matches the built geometry; 'th' is
    % prepended below (xsect = 'rect'), so both are defaulted here.
    Pv = ribDefaultParams(P);
    if ~isfield(P,'xsect')
        P.xsect = Pv.xsect;
    end
    if ~isfield(P,'th')
        P.th = Pv.th;
    end
    convStr = 'cw';
    if strcmp(Pv.taperConvention,'centerspacing')
        convStr = 'cs';
    end
    endStr = 'lr';
    if strcmp(Pv.mEndBC,'fixed')
        endStr = 'fx';
    end
    % Rib length: an explicit P.L / P.w (one constant L for every cell),
    % P.w_mirror (+ P.w_ctr; tip-to-tip widths at the mirror and centre
    % cells) or the L(a) rule; see ribLength. With ribTaperScheme = 'hole'
    % an '_o<oblong>' token follows, and wc is the real centre width.
    [Lc, Lsrc] = ribLength(Pv, Pv.a);
    if strcmp(Lsrc,'rule')
        Lstr = ['Lr',num2str(Pv.L_ref*1e9,'%.0f'),'nm_',...
                'ar',num2str(Pv.a_ref*1e9,'%.0f'),'nm_',...
                'dL',num2str(Pv.dLda,'%.4f')];
    elseif strcmp(Lsrc,'w_mirror')
        wEnds = 2*ribLength(Pv, Pv.a*[1, 1 - Pv.maxdef]);
        Lstr = ['wm',num2str(wEnds(1)*1e9,'%.0f'),'nm_wc',num2str(wEnds(2)*1e9,'%.0f'),'nm'];
    else
        Lstr = ['Lc',num2str(Lc*1e9,'%.0f'),'nm'];
    end
    % Hole-style taper (ribTaperScheme = 'hole'): oblong token. Written even
    % for oblong = 0, which differs from the 'rib' scheme.
    if strcmp(Pv.ribTaperScheme,'hole')
        ob = Pv.oblong;
        if isempty(ob)
            ob = 2.7;           % ribLength's default for an empty P.oblong
        end
        Lstr = [Lstr,'_o',num2str(ob,'%.4f')];
    end
    P.fileBase = [Pv.celltype,'_',...
              'a',num2str(Pv.a*1e9,'%.0f'),'nm_',...
              't',num2str(Pv.t*1e9,'%.0f'),'nm_',...
              's',num2str(Pv.s*1e9,'%.0f'),'nm_',...
              Lstr,'_',...
              'r1_',num2str(Pv.r1*1e9,'%.0f'),'nm_',...
              'r2_',num2str(Pv.r2*1e9,'%.0f'),'nm_',...
              'sw',num2str(Pv.d*180/pi,'%.0f'),'deg_',...
              'nc',num2str(Pv.ncellHalf,'%.0f'),'_',...
              'nd',num2str(Pv.ndef,'%.0f'),'_',...
              'd',num2str(Pv.maxdef,'%.4f'),'_',...
              Pv.taperFunc,'_',convStr,'_',...
              'ctr',num2str(Pv.ribatctr,'%.0f'),'_',...
              'az',num2str(Pv.airZOffset*1e9,'%.0f'),'nm_',...
              endStr];
    symTags = {'mevenx','X'; 'meveny','Y'; 'mevenz','Z'};
    for k = 1:size(symTags,1)
        if isfield(P,symTags{k,1})
            P.fileBase = [P.fileBase,'_',symTags{k,2},num2str(P.(symTags{k,1}))];
        end
    end
else
    P.fileBase = ['a',num2str(P.a*1e9,'%.0f'),'nm_',...
              'nh',num2str(P.nholes,'%.0f'),'_',...
              'nd',num2str(P.ndef,'%.0f'),'_',...
              'nw',num2str(P.wvgmir,'%.0f'),'_',...
              'w',num2str(P.w*1e9,'%.0f'),'nm_',...
              'hx',num2str(P.hx*1e9,'%.0f'),'nm_',...
              'hy',num2str(P.hy*1e9,'%.0f'),'nm_'];
    if isfield(P,'useManualGeom') && P.useManualGeom
        % Manual hole arrays (CreateNanobeamGeom ignores oblong/maxdef): name
        % the run by a hash of the arrays, so two manual designs never share
        % a fileBase and RunNanobeamFEM cannot reload the wrong cached result.
        % The token REPLACES the o/d tokens instead of following them, because
        % RunNanobeamFEM globs [fileBase,'*.mat'] and a formula-run name must
        % not be a prefix of a manual-run name. Keep this branch identical in
        % CreateFileBase.m and nanobeam/CreateFileBase.m.
        P.fileBase = [P.fileBase,'mg',manualGeomHash(P)];
    else
        P.fileBase = [P.fileBase,...
              'o',num2str(P.oblong,'%.4f'),'_',...
              'd',num2str(P.maxdef,'%.4f')];
    end
end

% cross-cell phononic shield tokens. Additive and field-guarded: a caller that
% does not set the shield fields produces a byte-identical filename. Kept in
% sync with nanobeam/CreateFileBase.m per CLAUDE.md - either copy can win the
% path lookup, so the shield must be encoded in both.
%
% THE nsy TOKEN ENCODES THE Y CONVENTION, NOT JUST THE COUNT, because
% P.nShieldY means two different devices depending on P.meveny:
%   abs(P.meveny) == 1 (or P.meveny absent)  HALF-Y build. P.nShieldY is the
%       cell count in the simulated y >= 0 half, the physical device has
%       2*P.nShieldY rows, and the shield is mirror-symmetric about the beam.
%       Token: nsyH<half>_nsyP<physical>, spelled out so the convention cannot
%       be misread from a filename months later. THIS STRING IS UNCHANGED - it
%       must stay byte for byte what it was, or every cached .mat/.mph under
%       test/ is orphaned.
%   P.meveny == 0                            FULL-Y build. P.nShieldY is the
%       ABSOLUTE row count, all of it on the +y side of the beam, and the
%       shield bottom is flush with the beam bottom. Token: nsyF<absolute>.
%
% Without the distinction a full-y run and a half-y run at the same P.nShieldY
% would produce the same P.fileBase, and RunNanobeamFEM.m:64 - which skips the
% entire solve whenever a matching .mat AND .mph already sit in datLoc - would
% hand back the other build's result with nothing in the log to say so. The
% same argument is why the PML length is in here: without that token a Q vs
% PMLLen convergence sweep would silently reload the first run.
if isfield(P,'nShieldX') && isfield(P,'nShieldY')
    if isfield(P,'meveny') && abs(P.meveny) < 1
        nsyStr = ['nsyF',num2str(P.nShieldY,'%.0f')];
    else
        nsyStr = ['nsyH',num2str(P.nShieldY,'%.0f'),'_',...
                  'nsyP',num2str(2*P.nShieldY,'%.0f')];
    end
    P.fileBase = [P.fileBase,'_',...
                  'csA',num2str(P.aShield*1e9,'%.0f'),'nm_',...
                  'csH',num2str(P.hShield*1e9,'%.0f'),'nm_',...
                  'csW',num2str(P.wShield*1e9,'%.0f'),'nm_',...
                  'nsx',num2str(P.nShieldX,'%.0f'),'_',...
                  nsyStr];
    if isfield(P,'shieldPadLen') && P.shieldPadLen > 0
        P.fileBase = [P.fileBase,'_pad',num2str(P.shieldPadLen*1e9,'%.0f'),'nm'];
    end
    if isfield(P,'shieldFillet') && ~strcmp(P.shieldFillet,'none')
        P.fileBase = [P.fileBase,'_fil',P.shieldFillet];
    end
    if isfield(P,'solveMechPML') && P.solveMechPML && isfield(P,'PMLLen')
        P.fileBase = [P.fileBase,'_pml',num2str(P.PMLLen*1e9,'%.0f'),'nm'];
    end
end

if strcmp(P.xsect,'tri')
    P.fileBase = [num2str(P.theta,'%.0f'),'o_',P.fileBase];
elseif strcmp(P.xsect,'rect')
    P.fileBase = ['th',num2str(P.th*1e9,'%.0f'),'nm_',P.fileBase];
end
if isfield(P,'rxtal') && isfield(P,'rxtalInFilename') && P.rxtalInFilename == 1
    P.fileBase = ['rxt',num2str(P.rxtal,'%.0f'),'o_',P.fileBase];
end
if isfield(P,'asymCav') && P.asymCav && isfield(P,'PL')
    P.fileBase = [P.fileBase,'_'...
                  'nmL',num2str(P.PL.nholes-P.PL.ndef,'%.0f'),'_',...
                  'nwL',num2str(P.PL.wvgmir,'%.0f')];
    if isfield(P.PL,'useManualGeom') && P.PL.useManualGeom
        % left-half manual arrays: own hash, or two asymmetric runs that
        % differ only on the left would share a fileBase
        P.fileBase = [P.fileBase,'_mgL',manualGeomHash(P.PL)];
    end
end
if isfield(P,'shave')
    P.fileBase = [P.fileBase,'_sh',num2str(P.shave*1e9,'%.0f'),'nm'];
end
if isfield(P,'strPoint') && isfield(P,'nItr')
    P.fileBase = ['sp',num2str(P.strPoint),'_',...
                  'itr',num2str(P.nItr),'_',P.fileBase];
end
if isfield(P,'asymCav') && P.asym
    P.fileBase = ['asym_',P.fileBase];
end
if isfield(P,'prefname')
    P.fileBase = [P.prefname,'_',P.fileBase];
end
if isfield(P,'filRad') && P.filRad > 0
    fBase = [fBase,'_Rfil_',num2str(P.filRad*1e9,'%.1f'),'nm'];
end

end

% =========================================================================
function h = manualGeomHash(P)
%MANUALGEOMHASH  8-hex-digit FNV-1a hash of the manual hole arrays.
%   Hashes P.a_hole, P.hx_hole, P.hy_hole (the arrays CreateNanobeamGeom reads
%   when P.useManualGeom = 1) printed in nm to 0.001 nm, so edits below 1 pm
%   keep the same name. a_hole(1) is left out when P.holeatctr = 1, where the
%   builder does not use it. With P.useManualWvgMir = 1 and P.wvgmir > 0 the
%   end-taper arrays P.a_wvgmir/hx_wvgmir/hy_wvgmir are hashed too; without
%   them the string, and so the token, is what it was before. Pure
%   arithmetic: the same arrays give the same token on every machine and
%   MATLAB release.
if ~all(isfield(P,{'a_hole','hx_hole','hy_hole'}))
    error('CreateFileBase:manualGeom',...
        'P.useManualGeom = 1 requires P.a_hole, P.hx_hole and P.hy_hole.');
end
aH = P.a_hole(:)';
if isfield(P,'holeatctr') && P.holeatctr
    aH = aH(2:end);
end
str = [sprintf('%.3f,',aH*1e9),';',...
       sprintf('%.3f,',P.hx_hole(:)'*1e9),';',...
       sprintf('%.3f,',P.hy_hole(:)'*1e9)];
if isfield(P,'useManualWvgMir') && P.useManualWvgMir && ...
        isfield(P,'wvgmir') && P.wvgmir > 0
    if ~all(isfield(P,{'a_wvgmir','hx_wvgmir','hy_wvgmir'}))
        error('CreateFileBase:manualWvgMir',...
            'P.useManualWvgMir = 1 requires P.a_wvgmir, P.hx_wvgmir and P.hy_wvgmir.');
    end
    str = [str,';w',sprintf('%.3f,',P.a_wvgmir(:)'*1e9),';',...
           sprintf('%.3f,',P.hx_wvgmir(:)'*1e9),';',...
           sprintf('%.3f,',P.hy_wvgmir(:)'*1e9)];
end
hv = uint64(2166136261);                        % FNV-1a 32-bit offset basis
for c = uint64(str)
    hv = mod(bitxor(hv,c)*uint64(16777619),uint64(4294967296));
end
h = sprintf('%08x',hv);
end